"""Generate docs/VIDEO_SCRIPT.md (4:30 voiceover) from the real reports and demo snapshots.

    python tasks.py video
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REP = ROOT / "eval" / "reports"
SNAP = ROOT / "demo_snapshots"
DELAY = 25  # seconds between steps in `present --auto --delay 25`


def load(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


def mmss(t: int) -> str:
    return f"{t // 60}:{t % 60:02d}"


def main() -> None:
    b = load(REP / "eval_B.json")
    org = load(REP / "organizer.json")["B"]
    rob = load(REP / "organizer_robustness.json")
    fz = load(REP / "fuzz.json")
    cong = load(SNAP / "01_congestion" / "report.json")
    wifi_off = load(SNAP / "02_wifi_insufficient" / "report.json")
    wifi = load(SNAP / "05_wifi_diagnosed" / "report.json")
    chaos = load(SNAP / "06_chaos_input" / "report.json")
    conf_lines = (SNAP / "04_conformance" / "output.txt").read_text(encoding="utf-8").splitlines()
    ev = {e["metric"]: e["value"] for e in wifi["supporting_evidence"]}
    preds = cong["predictions"]
    hits = sum(p["outcome"] == "hit" for p in preds)
    ns = chaos["normalization_summary"]
    sev = {(r["label"], r["level"]): r for r in rob["severity"]}
    blocked = cong["blocked_actions"][0]["reason"] if cong["blocked_actions"] else "-"

    t0 = 40  # present starts here
    steps = [
        ("Congestion", f"Five internal agents exchange typed NMP messages on one bus, and every message lands in an append-only log. "
                       f"Watch the predictions: before asking for evidence, the correlation agent writes down what it expects. "
                       f"{hits} of {len(preds)} come back as hits, and the miss is shown too. Result: *{cong['suspected_root_cause']}*, "
                       f"confidence {cong['confidence']:.2f}."),
        ("Wi-Fi without the agent", f"Same campus, a Wi-Fi complaint. Packet loss at AP_H3 is real, but nobody can see the radio. "
                                    f"So NetCoop says `insufficient_evidence` and names the missing signals: "
                                    f"{', '.join(s for s in wifi_off['missing_signals'] if 'AP_H3' in s and 'L_' not in s)}. "
                                    "No guessing."),
        ("Start the external agent", "Now we start a separate agent, written in Node.js, that speaks an older dialect: version 0.9, "
                                     "with its own field names. It joins mid-session, discovered from an allowlist, with no restart."),
        ("Conformance", f"Before we trust it, our conformance kit checks it: {sum(1 for x in conf_lines if x.startswith('PASS'))} of "
                        f"{len(conf_lines)} checks pass. That covers a valid card, valid replies, an error on malformed input, idempotency, "
                        "and tolerance of newer versions."),
        ("Wi-Fi again", f"Same incident file. The only difference is the new agent. Now: *{wifi['suspected_root_cause']}*. "
                        f"RSSI {ev.get('rssi_dbm', '?'):g} dBm, SNR {ev.get('snr_db', '?'):g} dB, retransmissions "
                        f"{ev.get('retransmission_pct', '?'):g}%. The gateway translated `signal`, `noise_margin` and `ap-h3` on the way in."),
        ("Chaos input", f"Real data is messy. This bundle mixes a legacy v0.9 block, seconds instead of milliseconds, fractions, "
                        f"mangled IDs, a ghost switch and an injection attempt. {ns['records_in']} records in, {ns['records_used']} used, "
                        f"{ns['records_quarantined']} quarantined, none silently dropped. Diagnosis: device overload on DEPT_CORE_SW_01."),
        ("Policy", f"Recommendations come only from a playbook and pass hard rules in code. Here: *{blocked}*. "
                   "Nothing is ever executed automatically."),
        ("Normal network", "And a healthy network is reported as healthy: `no_fault_detected`."),
    ]
    L = ["# Video script (4:30)", "",
         "Generated by `python tasks.py video` from `eval/reports/` and `demo_snapshots/`, so every number below is real.",
         "",
         "**Recording setup:** terminal ≥ 100 columns, font ≥ 16 pt, `NETCOOP_LLM` unset. Run `python tasks.py preflight`",
         f"first, then start recording and at **0:40** run `python tasks.py present --auto --delay {DELAY}`",
         f"(add `--no-color` for a light theme). Each step then gets ~{DELAY + 1} s of voiceover.", "",
         "| Time | On screen | Voiceover |", "|---|---|---|",
         "| 0:00–0:20 | Title: *NetCoop AI: multi-agent network fault diagnosis* | Campus networks fail in ways no single "
         "monitor can explain. NetCoop lets specialized agents argue it out, over a documented protocol, and "
         "produce one honest report. |",
         "| 0:20–0:40 | `docs/architecture.svg` | Five internal agents on a message bus with an event log. An A2A "
         "gateway for outside agents. Everything they know lives in config, not in code. The core is "
         "deterministic: same input, same report, byte for byte. |"]
    for i, (title, vo) in enumerate(steps):
        a, z = t0 + i * (DELAY + 1), t0 + (i + 1) * (DELAY + 1)
        L.append(f"| {mmss(a)}–{mmss(z)} | `present` step {i + 1}: {title} | {vo} |")
    end = t0 + len(steps) * (DELAY + 1)
    L.append(f"| {mmss(end)}–4:30 | README eval section | Measured, not claimed. On the organizer's own generator: "
             f"{org['per_label']['latency_spike']['accuracy']:.0%} / {org['per_label']['hardware_failure']['accuracy']:.0%} "
             f"correct, {org['per_label']['normal']['accuracy']:.0%} healthy. On our harder generator: "
             f"{b['precision_when_diagnosed']:.0%} right when it commits, {b['wrong_diagnosis_rate']:.1%} wrong. "
             f"60% corrupted input: {fz[-1]['accuracy']}. And we publish the weak spots: device overload "
             f"{b['per_fault']['device_overload']['accuracy']}, and hardware failure at a quarter of its severity "
             f"is mislabeled ({sev[('hardware_failure', 0.25)]['correct']:.0%} correct). |")
    L += ["", f"Runtime check: the intro is 40 s, then {len(steps)} steps × {DELAY + 1} s = {len(steps) * (DELAY + 1)} s, "
          f"ending at {mmss(end)}; the close runs to 4:30.", "",
          "**If a live step misbehaves while recording:** stop and re-record that segment from `demo_snapshots/<step>/timeline.html`."]
    out = ROOT / "docs" / "VIDEO_SCRIPT.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out} (ends at {mmss(end)} + close)")


if __name__ == "__main__":
    main()
