"""Generate docs/FRONTEND_API.md from the actual code + recorded fixtures (F1). `python tools/gen_frontend_api.py`.

Sources (nothing hand-maintained except the prose around them):
* routes, methods, parameters, request schemas, docstrings: the FastAPI app (`netcoop.api.main.app`, its OpenAPI)
  and the dashboard router (`netcoop.api.dashboard.router`);
* response examples, error examples: docs/frontend_fixtures/ (recorded from the real backend by
  tools/record_fixtures.py);
* SSE framing: produced by calling the real `sse_events()` on a fixture;
* message envelope and payload fields: the Pydantic models (`Message`, `PAYLOAD_MODELS`); JSON Schemas in docs/schemas/;
* security headers, CORS, static files, enums and thresholds: the module constants, Literal types and config/scoring.yaml.

`--check` exits 1 if the file on disk differs (used by the test suite).
"""

from __future__ import annotations

import asyncio
import json
import sys
import typing
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
FIX = ROOT / "docs" / "frontend_fixtures"
OUT = ROOT / "docs" / "FRONTEND_API.md"
MAX = 1800  # characters per inlined example


def j(obj: Any, limit: int = MAX) -> str:
    s = json.dumps(obj, indent=2, ensure_ascii=False)
    return s if len(s) <= limit else s[:limit].rstrip() + "\n  … (truncated; full example in the fixture file)"


def trim(payload: Any) -> Any:
    """Shorten long lists inside an example payload (keeps the first item, notes the count)."""
    if isinstance(payload, dict):
        return {k: trim(v) for k, v in payload.items()}
    if isinstance(payload, list) and len(payload) > 2:
        return [trim(payload[0]), f"… {len(payload) - 1} more"]
    if isinstance(payload, list):
        return [trim(x) for x in payload]
    return payload


def lit(t: Any, sep: str = ", ") -> str:
    args = typing.get_args(t)
    return sep.join(f"`{a}`" for a in args) if args else str(t)


def stype(s: dict[str, Any]) -> str:
    """Human type from a JSON Schema property (as generated by Pydantic)."""
    if "enum" in s:
        return ", ".join(f"`{v}`" for v in s["enum"])
    if "const" in s:
        return f"`{s['const']}`"
    if "anyOf" in s:
        return " or ".join(stype(x) for x in s["anyOf"])
    t = s.get("type", "object" if "$ref" in s else "any")
    if t == "string" and s.get("format"):
        return f"string ({s['format']})"
    if t == "string" and s.get("pattern"):
        return f"string matching `{s['pattern']}`"
    if t == "array":
        return f"array of {stype(s.get('items', {}))}"
    return t


def load_fixtures() -> tuple[list[dict[str, Any]], dict[str, Any], dict[str, list[dict[str, Any]]]]:
    index = json.loads((FIX / "index.json").read_text(encoding="utf-8"))
    examples = json.loads((FIX / "api_examples.json").read_text(encoding="utf-8"))
    exchanges = {f["name"]: json.loads((FIX / f["name"] / "api.json").read_text(encoding="utf-8")) for f in index}
    return index, examples, exchanges


def events_of(name: str) -> list[dict[str, Any]]:
    return [json.loads(x) for x in (FIX / name / "events.jsonl").read_text(encoding="utf-8").splitlines() if x.strip()]


def api_routes() -> list[Any]:
    from fastapi.routing import APIRoute

    from netcoop.api.main import app

    return [r for r in app.routes if isinstance(r, APIRoute)]


def find_exchange(route: Any, method: str, exchanges: dict[str, list[dict[str, Any]]]) -> dict[str, Any] | None:
    for flow in exchanges.values():
        for x in flow:
            path = x["path"].split("?")[0]
            if x["method"] == method and route.path_regex.match(path) and 200 <= x["status"] < 300:
                return x
    return None


def gen() -> str:
    from netcoop.api import dashboard as dash
    from netcoop.api.main import app
    from netcoop.config import load_config
    from netcoop.protocol.envelope import SCHEMA_VERSION, Message, MessageType
    from netcoop.protocol.findings import Prediction
    from netcoop.protocol.messages import (
        PAYLOAD_MODELS,
        SIMULATED_LABEL,
        Conflict,
        DiagnosisPayload,
        HumanDecisionPayload,
    )

    index, examples, exchanges = load_fixtures()
    openapi = app.openapi()
    cfg = load_config()
    L: list[str] = []
    w = L.append

    w("# NetCoop frontend API contract")
    w("")
    w("> **Generated** by `python tools/gen_frontend_api.py` from the code (FastAPI app, Pydantic models, module "
      "constants) and from fixtures recorded on the real backend (`tools/record_fixtures.py`). Do not edit by hand; "
      "a test fails if this file is stale.")
    w("")
    w(f"Protocol: NMP **{SCHEMA_VERSION}**. Base URL: `http://127.0.0.1:<port>` (`netcoop serve --port 8000`, the "
      "default; it binds loopback only). Mock without a backend: `python tools/mock_api.py` (same endpoints, recorded "
      "data; see [Mock](#mock-api-no-backend)).")
    w("")
    w("Contents: [Endpoints](#endpoints) · [Errors](#error-shapes) · [SSE stream](#sse-stream) · "
      "[Message payloads](#message-payloads-by-message_type) · [Flows](#flows) · [Security headers](#security-headers-csp-cors) · "
      "[Static UI](#static-ui-files) · [Fixtures](#fixtures) · [Mock](#mock-api-no-backend) · [Glossary](#glossary)")
    w("")

    # ---------------- endpoints ----------------
    w("## Endpoints")
    w("")
    w("| Method | Path | Purpose |")
    w("|---|---|---|")
    routes = api_routes()
    ui_routes = [r for r in dash.router.routes if not getattr(r, "include_in_schema", True)]
    for r in routes:
        for m in sorted(r.methods):
            w(f"| {m} | `{r.path}` | {(r.endpoint.__doc__ or r.name).strip().splitlines()[0]} |")
    for r in ui_routes:
        for m in sorted(r.methods):
            w(f"| {m} | `{r.path}` | UI static file (see [Static UI](#static-ui-files)) |")
    for p in ("/docs", "/redoc", "/openapi.json"):
        w(f"| GET | `{p}` | FastAPI's generated docs / OpenAPI document |")
    w("")
    for r in routes:
        for m in sorted(r.methods):
            op = openapi["paths"][r.path][m.lower()]
            w(f"### {m} `{r.path}`")
            w("")
            doc = (r.endpoint.__doc__ or "").strip()
            if doc:
                w(" ".join(x.strip() for x in doc.splitlines()))
                w("")
            params = op.get("parameters", [])
            if params:
                w("| Parameter | In | Type | Required | Default |")
                w("|---|---|---|---|---|")
                for p in params:
                    sch = p.get("schema", {})
                    w(f"| `{p['name']}` | {p['in']} | {sch.get('type', '')} | {'yes' if p.get('required') else 'no'} | "
                      f"{sch.get('default', '') if 'default' in sch else ''} |")
                w("")
            rb = op.get("requestBody")
            if rb:
                content = rb.get("content", {})
                if "application/json" in content:
                    ref = content["application/json"]["schema"].get("$ref", "")
                    name = ref.split("/")[-1]
                    sch = openapi["components"]["schemas"].get(name, content["application/json"]["schema"])
                    w("Request body (JSON Schema, from the code):")
                    w("```json")
                    w(j(sch))
                    w("```")
                    w("")
            if r.path == "/incidents" and m == "POST":
                w("Request body: the raw incident bundle (JSON or CSV bytes, ≤ 10 MB), same format as "
                  "`data/scenarios/<name>/incident.json`. The response is the full report (see "
                  "`docs/frontend_fixtures/*/report.json`). Invalid input still answers **200** with `status: failed`.")
                w("")
            if r.path.endswith("/stream"):
                w("Response: `text/event-stream`, see [SSE stream](#sse-stream).")
                w("")
                continue
            if r.path.endswith("report.csv"):
                w("Response: `text/plain` CSV (cells starting with `= + - @` are prefixed with `'`). Real example:")
                w("```")
                w("\n".join(examples["GET /incidents/{id}/report.csv"].splitlines()[:4]))
                w("```")
                w("")
                continue
            ex = None
            if r.path == "/scenarios":
                ex = examples["GET /scenarios"]
            elif r.path == "/topology":
                ex = trim(examples["GET /topology"])
            elif r.path == "/agents":
                ex = examples["GET /agents (wireless agent joined)"]
            elif r.path == "/incidents" and m == "GET":
                ex = examples["GET /incidents?limit=50"][:2]
            else:
                x = find_exchange(r, m, exchanges)
                ex = trim(x["response"]) if x else None
            if ex is not None:
                w("Response `200` (real example):")
                w("```json")
                w(j(ex))
                w("```")
                w("")
            if r.path == "/agents":
                w("Without the agent running, the same call returns:")
                w("```json")
                w(j(examples["GET /agents (wireless agent not running)"]))
                w("```")
                w("")

    # ---------------- errors ----------------
    w("## Error shapes")
    w("")
    w("Handled errors: `{\"detail\": {\"code\": <CODE>, \"detail\": <text>}}`. Body validation errors: FastAPI's "
      "`422 {\"detail\": [ {type, loc, msg, input, ctx} ]}`. Unknown routes: `404 {\"detail\": \"Not Found\"}`. Any "
      "unhandled exception: `500 {\"error\": {\"code\": \"INTERNAL\", \"detail\": \"internal error\"}}` (no stack "
      "traces). Real responses:")
    w("")
    for k, v in examples["errors"].items():
        w(f"* **{k}**: `{json.dumps(v, ensure_ascii=False)[:300]}`")
    w("")

    # ---------------- SSE ----------------
    w("## SSE stream")
    w("")
    w("`GET /incidents/{incident_id}/stream?delay_ms=<0..2000>`: replays the run's event log (`events.jsonl`) in "
      "`seq` order, then ends. The run is already complete when you stream it: start a run, get its `incident_id`, then "
      "open the stream. `delay_ms` (clamped to 0–2000) is the pause after each message; the built-in dashboard uses 240 "
      "(1×) and 120 (2×). Headers: `Content-Type: text/event-stream`, `Cache-Control: no-cache`.")
    w("")
    w("Event names: `message` (one NMP message as JSON in `data`, `id` = its `seq`) and a final `end` "
      "(`data: {\"messages\": <count>}`). Exact frames produced by the server code (first two messages of the "
      "`normal` fixture, data shortened here):")
    w("")

    async def frames() -> list[str]:
        out = []
        async for f in dash.sse_events(FIX / "normal" / "events.jsonl", 0):
            out.append(f)
        return out

    fr = asyncio.run(frames())
    w("```")
    for f in fr[:2]:
        head, data = f.split("data: ", 1)
        w(head + "data: " + data.strip()[:160] + " …")
        w("")
    w(fr[-1].strip())
    w("```")
    w("")
    w("Clients should parse each `data` as one JSON document, order by `seq` (the server already sends them in order) "
      "and render every string as text. Device names and limitations can contain anything the input contained. "
      "Messages appended after the report (`human_decision`, `remediation_plan`) are in the log too: re-open the "
      "stream or `GET /incidents/{id}/events` after approving.")
    w("")
    w("### Envelope (every message)")
    w("")
    w("| Field | Type |")
    w("|---|---|")
    props = Message.model_json_schema()["properties"]
    for name in Message.model_fields:
        cell = stype(props[name]).replace("|", "\\|")  # a literal | would split the Markdown cell
        w(f"| `{name}` | {cell} |")
    w("")
    w(f"`message_type` ∈ {lit(MessageType)}. JSON Schema: `docs/schemas/envelope.schema.json`.")
    w("")

    # ---------------- payloads ----------------
    w("## Message payloads by message_type")
    w("")
    w("Every example below is the first real message of that type in a recorded fixture (long lists shortened). "
      "Schemas: `docs/schemas/payload.<message_type>.schema.json`.")
    w("")
    seen: dict[str, tuple[str, dict[str, Any]]] = {}
    order = ["normal", "congestion", "weak_wifi_after", "interop_llm_hint", "approved_action_plan", "malformed_input_error"]
    for name in order + [f["name"] for f in index if f["name"] not in order]:
        for e in events_of(name):
            seen.setdefault(e["message_type"], (name, e))
    for mt in typing.get_args(MessageType):
        model = PAYLOAD_MODELS[mt]
        w(f"### `{mt}`")
        w("")
        fields = ", ".join(f"`{k}`" for k in model.model_fields)
        w(f"Payload fields ({model.__name__}): {fields}.")
        w("")
        if mt in seen:
            src, e = seen[mt]
            ex = {k: e[k] for k in ("seq", "message_type", "sender", "recipient", "status")}
            ex["payload"] = trim(e["payload"])
            w(f"Real example (`docs/frontend_fixtures/{src}/events.jsonl`, seq {e['seq']}):")
            w("```json")
            w(j(ex))
            w("```")
        else:
            w("_No recorded example._")
        w("")

    # ---------------- flows ----------------
    w("## Flows")
    w("")
    w("**Start a run and get its incident_id.** `POST /scenarios/{name}/run?external=true` → `{incident_id, status}` "
      "(names from `GET /scenarios`). The call returns when the diagnosis is complete. Then "
      "`GET /incidents/{incident_id}/stream?delay_ms=240` for the animated replay and `GET /incidents/{id}/report` for "
      "the final report. Upload your own bundle with `POST /incidents` (body = bundle bytes; response = report, whose "
      "`incident_id` you use the same way). incident_ids are generated by the server (`^INC-[0-9A-Z]{4,12}$`).")
    w("")
    w("**List / reopen past runs.** `GET /incidents?limit=50` (newest first; `limit` 1–500) → rows "
      "`{incident_id, status, suspected_root_cause, confidence, created_at}`. Reopen one with its `/report`, `/events` or "
      "`/stream`.")
    w("")
    w("**Approve / reject an action.** Action ids are in the report: `action_details[].id` (allowed and blocked, each with "
      "`allowed` and `rule_id`) and `blocked_actions[].action_id`. `POST /incidents/{id}/feedback` "
      "`{action_id, decision: approve|reject, note?}` (note ≤ 500 chars, stored in SQLite, never put in the log). "
      "Response `{id, executed: false, event_seq, message_id, policy, plan_seq, plan}`:")
    w("")
    w("* reject → a `human_decision` event; `policy`/`plan` are null;")
    w("* approve of an action the policy blocks → `human_decision`; `policy: {allowed: false, rule_id, reason, "
      "checked_at}`; `plan: null` (fixture `blocked_action_r1`);")
    w(f"* approve of an allowed action → `human_decision` + `remediation_plan` labelled \"{SIMULATED_LABEL}\" with "
      "`steps` and `rollback` (fixture `approved_action_plan`).")
    w("")
    w("Nothing is executed, and the report never changes. An `action_id` that is not in the report → `404 UNKNOWN_ACTION`.")
    w("")
    hd = HumanDecisionPayload.model_fields
    w(f"`human_decision` payload fields: {', '.join(f'`{k}`' for k in hd)}.")
    w("")
    w("**External agents / A2A join.** `GET /agents` → `external: {agent_id: status}` (`joined` or `unreachable`; the "
      "allowlist is `config/agents.yaml`) and `details` (card name/version and capabilities when joined, or the error). "
      "Discovery runs on each call and at the start of each run, so an agent that starts later joins the **next** run "
      "with no restart. In a run, a joined agent is a `sender` that is not one of NetCoop's internal agents (here "
      "`wireless_agent`); its messages carry the limitation `DIALECT_TRANSLATED` and its findings carry `version`/"
      "`alias`/`unit`/`entity` transforms (fixture `weak_wifi_after`).")
    w("")
    internal = sorted(set(cfg.agents["internal"]) | {"normalizer", "orchestrator"})
    w(f"**Agent list.** Internal agents (`config/agents.yaml`): {', '.join(f'`{a}`' for a in internal)}. Post-run "
      "senders: `human_operator` (human_decision), `remediation_planner` (remediation_plan). `triage_agent` only "
      "runs when `NETCOOP_LLM` is not `off` and the bundle has a complaint.")
    w("")

    # ---------------- headers ----------------
    w("## Security headers (CSP, CORS)")
    w("")
    w("UI responses (`/`, `/dashboard`, `/dashboard/*`, `/ui/*`) carry, verbatim:")
    w("```")
    for k, v in dash.SECURITY_HEADERS.items():
        w(f"{k}: {v}")
    w("```")
    cors = next(m for m in app.user_middleware if "CORS" in getattr(m.cls, "__name__", ""))
    w("CORS (Starlette `CORSMiddleware`), verbatim from the code:")
    w("```")
    w(json.dumps(cors.kwargs))
    w("```")
    w("So a UI served by `netcoop serve` itself (same origin) needs no CORS; a dev server on port 5173 is allowed. "
      "The CSP means no inline `<script>`, no `style=\"\"` attributes, no CDN or remote fonts, and every request goes "
      "to the same origin.")
    w("")

    # ---------------- static ----------------
    w("## Static UI files")
    w("")
    w(f"* Built-in dashboard: `netcoop/api/static/` → `/` and `/dashboard` (dashboard.html), `/dashboard/<name>` for "
      f"{', '.join(f'`{k}`' for k in dash._FILES)} (fixed allowlist).")
    w(f"* `netcoop serve --ui <folder>`: `<folder>/index.html` at `/`, any file under the folder at `/ui/<path>` "
      f"(extensions {' '.join(sorted(dash.UI_TYPES))}; resolved path must stay inside the folder). `/dashboard` still "
      "serves the built-in UI. New UIs go in `dashboard_v2/` (a starter is there). Without `--ui`, behaviour is "
      "unchanged and `/ui/*` is 404.")
    w("")

    # ---------------- fixtures ----------------
    w("## Fixtures")
    w("")
    w("`docs/frontend_fixtures/<name>/`: `events.jsonl` (exactly what `/events` and `/stream` serve), `report.json`, "
      "`api.json` (every HTTP exchange of the flow). `index.json` lists them; `api_examples.json` has the other "
      "endpoints and real errors. Re-record: `python tools/record_fixtures.py --llm`.")
    w("")
    w("| Fixture | incident_id | status | messages | What it shows |")
    w("|---|---|---|---|---|")
    for f in index:
        w(f"| `{f['name']}` | {f['incident_id']} | {f['status']} | {f['messages']} | {f['about']} |")
    w("")

    # ---------------- mock ----------------
    w("## Mock API (no backend)")
    w("")
    w("```")
    w("python tools/mock_api.py                     # http://127.0.0.1:8000/, built-in dashboard")
    w("python tools/mock_api.py --ui dashboard_v2   # your UI")
    w("python tools/mock_api.py --port 8080 --agent joined")
    w("```")
    w("Standard library only. Same endpoints, bodies, errors, headers and SSE framing. `POST /scenarios/{name}/run` "
      "returns a new `INC-MOCKnnnn` copy of the recorded run. `weak_wifi` returns the *before* fixture until "
      "`POST /mock/agent/join` (or `--agent joined`), then *after*; `interop` includes the LLM hint. The stream honours "
      "`delay_ms`; `&timing=recorded` replays the recorded gaps between messages. Feedback appends `human_decision` "
      "and, for allowed approvals, `remediation_plan`, like the server. Mock-only: `POST /mock/agent/join|leave`, "
      "`GET /mock/fixtures`. `POST /incidents` replays the malformed-input fixture for invalid JSON and answers "
      "`501 MOCK_UNSUPPORTED` for anything else.")
    w("")

    # ---------------- glossary ----------------
    sc = cfg.scoring
    w("## Glossary")
    w("")
    w("* **incident**: one diagnosis run over one input bundle, identified by `incident_id`; its event log is the "
      "source of truth.")
    w("* **finding**: one agent's measured observation: `finding_id`, `metric` (`config/metrics.yaml`), `entity "
      "{type, id}`, `value` + canonical `unit`, `window`, `aggregation`, `severity` "
      f"({lit(typing.get_type_hints(__import__('netcoop.protocol.findings', fromlist=['x']).Finding)['severity'])}), "
      "`data_quality`, `transforms`, `source_refs`.")
    w("* **hypothesis**: a candidate `fault_type` attached to an entity, scored "
      "`score = clamp(support − contra_penalty × contra, 0, 1) × quality` from expected / contradicting signals in "
      "`config/signatures.yaml`; carries `supporting_finding_ids`, `contradicting_finding_ids`, `missing_signals`.")
    w(f"* **prediction**: logged before its evidence is requested; outcome {lit(Prediction.model_fields['outcome'].annotation)}. "
      "**hit** = the evidence matched the expectation (counts as support), **miss** = it did not (counts against), "
      "**unknown** = nobody could provide the signal.")
    w("* **normalization transform**: one recorded change to raw input: `{step, field, from, to, reason}`, step ∈ "
      "`version`, `alias`, `unit`, `entity`, … (e.g. `retx` `0.208 fraction` → `retransmission_pct` `20.8 pct`). "
      "Unrecoverable data is quarantined, never silently dropped.")
    w(f"* **conflict** ({lit(Conflict.model_fields['type'].annotation)}): **C1** value: the same metric and entity "
      f"differ by more than {sc['conflicts']['c1_relative_diff']:.0%}, so the fresher value wins (then sample count, "
      "then source priority). **C2** state: a device is reported `down` but has newer telemetry, or a metric names a "
      "link missing from the topology; the source is marked stale. **C3** hypothesis: the top two scores are within the "
      "margin; prediction rounds try to separate them.")
    w(f"* **status** ({lit(DiagnosisPayload.model_fields['status'].annotation)}): `diagnosed` = a signature matched with "
      f"enough coverage and margin; `probable` = the top two are closer than {sc['status']['min_margin']} (both "
      f"reported); `insufficient_evidence` = coverage below {sc['status']['min_top_coverage']} (`status_reason: "
      "data_missing`) or an anomaly that matches no signature (`no_signature_match`); `no_fault_detected` = nothing "
      f"≥ high and top score below {sc['status']['min_top_score']}; `failed` = the input or an agent failed. Wording is "
      "always \"Likely …\".")
    w(f"* **confidence_category** ({lit(DiagnosisPayload.model_fields['confidence_category'].annotation)}): `high` if "
      f"confidence ≥ {sc['confidence']['high_min']} and margin ≥ {sc['confidence']['high_min_margin']}; `medium` if "
      f"≥ {sc['confidence']['medium_min']}; otherwise `low`. It is capped at `medium` when an agent failed or a C2 "
      "conflict is unresolved. `confidence` = top score, 2 decimals.")
    w("* **decision_source**: always `deterministic_scoring`. An LLM `hint` can only add a hypothesis to test, never "
      "set the cause, confidence, status or actions.")
    w("")
    return "\n".join(L) + "\n"


def main() -> int:
    text = gen()
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
